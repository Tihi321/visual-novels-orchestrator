import { readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { emitScripts, translatableStrings } from '../src/engine/renpy/emit'
import { emitPuzzleData, playedPuzzles, puzzlePics } from '../src/engine/renpy/puzzles'
import { defaultCues } from '../src/engine/renpy/stage'
import { knightsCoreSchema, puzzleCoreSchema, puzzleEntrySchema } from '../src/shared/puzzle'
import type { PuzzleEntry } from '../src/shared/puzzle'
import { buildBook, storyInputSchema } from '../src/engine/vn/story'
import { editionSchema, vnBookSchema } from '../src/shared/vn'
import type { VnBook } from '../src/shared/vn'

const fixture = JSON.parse(readFileSync(path.resolve(__dirname, 'fixtures', 'puzzles', 'murdle-medium-1.json'), 'utf8')) as Record<string, unknown> & { names: Record<string, string>; text: Record<string, string> }
const entry = (over: Partial<PuzzleEntry> = {}): PuzzleEntry =>
  puzzleEntrySchema.parse({ key: 'dinner', kind: 'murdle', data: puzzleCoreSchema.parse(fixture), names: fixture.names, text: fixture.text, verified: { unique: true, deducible: true, score: 37, textChecked: true, by: 'test' }, ...over })

const book = (over: Partial<PuzzleEntry> = {}): VnBook => {
  const b = buildBook(
    storyInputSchema.parse({
      title: 'The Cold Dinner',
      characters: [{ name: 'Hartley', looks: 'a tired detective' }],
      places: [{ name: 'Manor', looks: 'a dark dining room' }],
      chapters: [
        { title: 'The Body', choices: [{ text: 'Go on', to: 2 }], scenes: [{ place: 'manor', beats: [{ cast: ['hartley'] }, { speaker: 'Hartley', text: 'The dinner went cold.' }, { puzzle: 'dinner' }, { text: 'It was over.' }] }] },
        { title: 'The Bad End', ending: 'Nobody was caught.', scenes: [{ place: 'manor', beats: [{ text: 'The culprit left.' }] }] }
      ]
    }),
    { slug: 'dinner', lang: 'en' }
  ).book
  return vnBookSchema.parse({ ...b, puzzles: [entry(over)] })
}
const emit = (b: VnBook) => emitScripts({ book: b, cues: defaultCues(b, { musicIds: [] }) })

describe('a puzzle beat in the script', () => {
  it('calls the puzzle label with its data, after a beat comment', () => {
    const ch = emit(book()).files['ch01.rpy']!
    expect(ch).toContain('    # beat:ch01.s01.b003 puzzle:dinner\n    call vno_puzzle_play("dinner", vno_puzzle_data["dinner"])\n')
    expect(ch.indexOf('puzzle:dinner')).toBeGreaterThan(ch.indexOf('The dinner went cold.'))
    expect(ch.indexOf('puzzle:dinner')).toBeLessThan(ch.indexOf('It was over.'))
    expect(ch).not.toContain('if not _return')
  })

  it('onFail chapter jumps to that chapter when the result is false; a chapter that is not there only warns', () => {
    const r = emit(book({ onFail: { mode: 'chapter', to: 2 } }))
    expect(r.files['ch01.rpy']).toContain('    call vno_puzzle_play("dinner", vno_puzzle_data["dinner"])\n    if not _return:\n        jump ch_02\n')
    const none = emit(book({ onFail: { mode: 'chapter', to: 9 } }))
    expect(none.files['ch01.rpy']).not.toContain('jump ch_09')
    expect(none.warnings.join(' ')).toMatch(/sends a failed player to chapter 9, which does not exist/)
    expect(emit(book({ onFail: { mode: 'continue', maxTries: 2 } })).files['ch01.rpy']).not.toContain('if not _return')
  })

  it('a clue found earlier is announced right after its beat', () => {
    const ch = emit(book({ clueAt: { c1: 'ch01.s01.b002', c2: 'ch01.s01.b002' } })).files['ch01.rpy']!
    const at = ch.indexOf('The dinner went cold.')
    expect(ch.slice(at, at + 220)).toContain('    $ vno_clue_found("dinner", "c1")\n    $ vno_clue_found("dinner", "c2")\n')
  })

  it('a puzzle that is not in the book is skipped with a warning', () => {
    const b = book()
    b.puzzles = []
    const r = emit(b)
    expect(r.files['ch01.rpy']).not.toContain('vno_puzzle_play')
    expect(r.warnings.join(' ')).toMatch(/puzzle dinner is not in the book/)
  })
})

describe('the puzzle data file', () => {
  it('has names and clue texts as translatable strings and plain data for the rest, without a seed', () => {
    const r = emit(book({ onFail: { mode: 'continue', maxTries: 2 }, hints: false, clueAt: { c1: 'ch01.s01.b002' } }))
    const data = r.files['vno_puzzles_data.rpy']!
    expect(data.startsWith('# Generated by VN Studio.')).toBe(true)
    expect(data).toContain('define vno_puzzle_data = {\n    "dinner": {"format": 1, "kind": "murdle", "size": 3, ')
    expect(data).toContain(`"s1": _("${fixture.names.s1}")`)
    expect(data).toContain(`"c1": _("${fixture.text.c1}")`)
    expect(data).toContain(`"murder": _("${fixture.text.murder}")`)
    expect(data).toContain('"hints": False')
    expect(data).toContain('"onFail": {"mode": "continue", "maxTries": 2}')
    expect(data).toContain('"at": "ch01.s01.b002"')
    expect(data).not.toContain('"seed"')
    expect(data).not.toContain('"band"')
    expect(emitPuzzleData(book())).toContain('"hints": True')
  })

  it('a book with no puzzle beat has no data file, and a puzzle no beat plays is not written', () => {
    const none = buildBook(storyInputSchema.parse({ title: 'T', characters: [{ name: 'A' }], places: [{ name: 'P' }], chapters: [{ title: 'c', scenes: [{ place: 'p', beats: [{ text: 'Hi.' }] }] }] }), { slug: 't', lang: 'en' }).book
    expect(emit(none).files['vno_puzzles_data.rpy']).toBeUndefined()
    const unplayed = vnBookSchema.parse({ ...none, puzzles: [entry()] })
    expect(playedPuzzles(unplayed)).toEqual([])
    expect(emit(unplayed).files['vno_puzzles_data.rpy']).toBeUndefined()
  })

  it('names and clue texts are translatable and an edition picks its own words', () => {
    const b = book()
    const strings = translatableStrings(b)
    const names = strings.filter((s) => s.what.startsWith('puzzle dinner name of'))
    const clues = strings.filter((s) => /^puzzle dinner (clue c\d+|murder note)$/.test(s.what))
    expect(names).toHaveLength(Object.keys(fixture.names).length)
    expect(clues).toHaveLength(Object.keys(fixture.text).length)
    const hr = editionSchema.parse({ lang: 'hr', title: 'Hladna večera', chapterTitles: {}, choiceTexts: {}, endings: {}, characterNames: {}, beats: {}, puzzles: { dinner: { names: { s1: 'Ana' }, text: { c1: 'Ana nije bila u knjižnici.' } } } })
    expect(names.find((s) => s.what.endsWith('of s1'))!.pick(hr)).toBe('Ana')
    expect(names.find((s) => s.what.endsWith('of s2'))!.pick(hr)).toBeUndefined()
    expect(clues.find((s) => s.what.endsWith('clue c1'))!.pick(hr)).toBe('Ana nije bila u knjižnici.')
    expect(translatableStrings(buildBook(storyInputSchema.parse({ title: 'T', characters: [{ name: 'A' }], places: [{ name: 'P' }], chapters: [{ title: 'c', scenes: [{ place: 'p', beats: [{ text: 'Hi.' }] }] }] }), { slug: 't', lang: 'en' }).book).some((s) => s.what.startsWith('puzzle'))).toBe(false)
  })
})

describe('pictures in the headers of a puzzle', () => {
  it('a character link is its neutral sprite, an image link its picture; a place has none; the images are marked as used', () => {
    const b = book({ links: { s1: { type: 'character', key: 'hartley' }, w1: { type: 'image', key: 'rope' }, p1: { type: 'place', key: 'manor' } } })
    b.images = [{ key: 'rope', description: 'a coil of rope', display: 'insert' }]
    expect(puzzlePics(b, b.puzzles![0]!)).toEqual({ s1: 'hartley neutral', w1: 'cg rope' })
    const r = emit(b)
    expect(r.files['vno_puzzles_data.rpy']).toContain('"pics": {"s1": "hartley neutral", "w1": "cg rope"}')
    expect(r.used.sprites).toContainEqual({ charKey: 'hartley', expression: 'neutral' })
    expect(r.used.cgs).toContainEqual({ key: 'rope', display: 'insert' })
    // a link to something the book does not have gives no picture
    const none = book({ links: { s1: { type: 'character', key: 'hartley' } } })
    none.characters = []
    expect(puzzlePics(none, none.puzzles![0]!)).toEqual({})
    expect(emit(book()).files['vno_puzzles_data.rpy']).not.toContain('"pics"')
  })
})

describe('a Knights and Knaves puzzle in the script', () => {
  const kk = JSON.parse(readFileSync(path.resolve(__dirname, 'fixtures', 'puzzles', 'knights-4-medium-3.json'), 'utf8')) as Record<string, unknown> & { names: Record<string, string>; text: Record<string, string> }
  const withKk = (links?: PuzzleEntry['links']): VnBook => {
    const b = book()
    b.puzzles = [puzzleEntrySchema.parse({ key: 'dinner', kind: 'knights', data: knightsCoreSchema.parse(kk), names: kk.names, text: kk.text, ...(links ? { links } : {}), verified: { unique: true, deducible: true, score: 5, textChecked: true, by: 'test' } })]
    return b
  }

  it('is written as plain data with the statements and names as translatable strings, and the call is the same', () => {
    const r = emit(withKk({ k1: { type: 'character', key: 'hartley' } }))
    expect(r.files['ch01.rpy']).toContain('call vno_puzzle_play("dinner", vno_puzzle_data["dinner"])')
    const data = r.files['vno_puzzles_data.rpy']!
    expect(data).toContain('"kind": "knights"')
    expect(data).toContain('"speakers": ["k1", "k2", "k3", "k4"]')
    expect(data).toContain('"statements": [{"id": "t1"')
    expect(data).toContain('"solution": {"k1": "')
    expect(data).toContain(`"intro": _("${kk.text.intro}")`)
    expect(data).toContain('"pics": {"k1": "hartley neutral"}')
    expect(data).not.toContain('"seed"')
    const strings = translatableStrings(withKk()).filter((s) => s.what.startsWith('puzzle dinner'))
    expect(strings.length).toBe(Object.keys(kk.names).length + Object.keys(kk.text).length)
    expect(strings.some((s) => s.what === 'puzzle dinner clue intro')).toBe(true)
  })
})
