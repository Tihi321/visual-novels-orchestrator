import { useMemo, useState, type ReactNode } from 'react'
import type { AssetView, ProjectDetail } from '../../../shared/protocol'
import { pickFile, sendCommand } from '../../api'
import { groupAssets, isAudioPath, isImagePath, readyCount, reviewBadge } from '../../lib/assets'
import { engineChoices } from '../../lib/engines'
import { projectAssetUrl } from '../../lib/urls'
import { useVn } from '../../store/hooks'
import { Modal, Pill, useRecentError } from '../common'

export function AssetsTab({ slug }: { slug: string; detail: ProjectDetail }) {
  const assetMap = useVn((s) => s.assets[slug])
  const voiceOn = useVn((s) => s.details[slug]?.settings.voice.enabled ?? false)
  const [showOrphans, setShowOrphans] = useState(false)
  const all = useMemo(() => Object.values(assetMap ?? {}), [assetMap])
  const visible = useMemo(() => all.filter((a) => showOrphans || !a.orphaned), [all, showOrphans])
  const groups = useMemo(() => groupAssets(visible), [visible])
  const orphans = all.length - all.filter((a) => !a.orphaned).length
  const error = useRecentError(slug)

  if (!assetMap) return <div className="dim">Loading assets...</div>
  return (
    <div className="stack" data-testid="tab-assets-body">
      <div className="row spread">
        <div className="dim">
          {all.length} assets. Edits to an asset only queue a build; they never restart the pipeline. A replaced or locked asset is never regenerated by the pipeline.
        </div>
        <label className="inline">
          <input type="checkbox" checked={showOrphans} onChange={(e) => setShowOrphans(e.target.checked)} />
          Show unused ({orphans})
        </label>
      </div>
      {error && <div className="bad-text">{error}</div>}
      <Group title="Backgrounds" assets={groups.backgrounds} slug={slug} />
      <GroupBox title="Characters" count={groups.characters.length}>
        {groups.characters.map((c) => (
          <div key={c.key} className="char-group" data-testid={`char-${c.key}`}>
            <div className="row">
              <b>{c.key}</b>
              <span className="dim">sheet and {c.sprites.length} sprites</span>
            </div>
            <div className="grid assets">
              {c.sheet && <AssetCard asset={c.sheet} slug={slug} />}
              {c.sprites.map((a) => (
                <AssetCard key={a.id} asset={a} slug={slug} small />
              ))}
            </div>
          </div>
        ))}
      </GroupBox>
      <Group title="Cover" assets={groups.cover} slug={slug} />
      <Group title="Music" assets={groups.music} slug={slug} />
      {(voiceOn || groups.voice.length > 0) && <Group title="Voice references" assets={groups.voice} slug={slug} />}
      {!all.length && <div className="dim">No assets yet. Run the pipeline (the art plan step creates them).</div>}
    </div>
  )
}

function GroupBox({ title, count, children }: { title: string; count: number; children: ReactNode }) {
  if (!count) return null
  return (
    <details open className="asset-group">
      <summary>
        <span className="section-title">{title}</span> <span className="dim">{count}</span>
      </summary>
      <div className="stack">{children}</div>
    </details>
  )
}

function Group({ title, assets, slug }: { title: string; assets: AssetView[]; slug: string }) {
  const { ready, total } = readyCount(assets)
  if (!total) return null
  return (
    <details open className="asset-group" data-testid={`group-${title.toLowerCase().replace(/\s+/g, '-')}`}>
      <summary>
        <span className="section-title">{title}</span>{' '}
        <span className="dim">
          {ready} of {total} ready
        </span>
      </summary>
      <div className="grid assets">
        {assets.map((a) => (
          <AssetCard key={a.id} asset={a} slug={slug} />
        ))}
      </div>
    </details>
  )
}

function AssetCard({ asset, slug, small }: { asset: AssetView; slug: string; small?: boolean }) {
  const rev = useVn((s) => s.assetRev[`${slug}:${asset.id}`] ?? 0)
  const [regen, setRegen] = useState(false)
  const [zoom, setZoom] = useState(false)
  const [pendingRev, setPendingRev] = useState<number | null>(null)
  const regenerating = pendingRev !== null && pendingRev === rev
  const badge = reviewBadge(asset)
  const audio = asset.kind === 'music' || asset.kind === 'voiceRef'
  const file = asset.fileRel
  const versionNumbers = Object.keys(asset.versionFiles).map(Number).sort((a, b) => a - b)
  const studio = asset.kind === 'voiceRef' ? null : asset.kind === 'music' ? 'Chiptune Studio' : 'Pixel Studio'
  const opened = useVn((s) => s.studioOpened[`${slug}:${asset.id}`])
  const warnings = asset.versions.find((v) => v.n === asset.selected)?.warnings ?? []
  const selectedVersion = asset.versions.find((v) => v.n === asset.selected)

  const upload = () =>
    void pickFile(audio ? 'Choose an audio file' : 'Choose an image', audio ? 'audio' : 'image').then((f) => {
      if (f) sendCommand({ type: 'replaceAsset', slug, id: asset.id, file: f })
    })

  return (
    <div className={`asset-card ${asset.orphaned ? 'orphan' : ''}`} data-testid={`asset-${asset.id}`}>
      <div className={`asset-media ${small ? 'small' : ''}`}>
        {file && isImagePath(file) && <img src={projectAssetUrl(slug, file, rev)} alt={asset.id} loading="lazy" onClick={() => setZoom(true)} />}
        {file && isAudioPath(file) && <audio controls preload="none" src={projectAssetUrl(slug, file, rev)} data-testid={`audio-${asset.id}`} />}
        {!file && <div className="dim">{audio ? 'no audio yet' : 'no image yet'}</div>}
        {regenerating && <div className="media-busy">regenerating...</div>}
      </div>
      <div className="row" style={{ marginTop: 4 }}>
        <b className="ellipsis" title={asset.id}>
          {asset.id}
        </b>
      </div>
      <div className="row">
        <Pill tone={badge.tone} testId={`review-${asset.id}`}>
          {badge.label}
        </Pill>
        {asset.source === 'custom' && <Pill tone="accent">custom</Pill>}
        {asset.locked && <Pill tone="warn">locked</Pill>}
        {selectedVersion?.custom && asset.source === 'generated' && <Pill tone="accent">edited by hand</Pill>}
        {asset.orphaned && <Pill>unused</Pill>}
      </div>
      {warnings.length > 0 && (
        <div className="warn ellipsis" title={warnings.join('\n')} data-testid={`warnings-${asset.id}`}>
          {warnings[0]}
        </div>
      )}
      {asset.review?.note && (
        <div className="dim ellipsis" title={asset.review.note}>
          {asset.review.note}
        </div>
      )}
      {!small && asset.prompt && (
        <div className="dim prompt" title={asset.prompt}>
          {asset.prompt}
        </div>
      )}
      {versionNumbers.length > 0 && (
        <div className="versions" data-testid={`versions-${asset.id}`}>
          {versionNumbers.map((n) => {
            const rel = asset.versionFiles[n]!
            const selected = asset.source === 'generated' && asset.selected === n
            return (
              <button
                key={n}
                className={selected ? 'ver on' : 'ver'}
                title={`Use version ${n}`}
                onClick={() => sendCommand({ type: 'pickAssetVersion', slug, id: asset.id, n })}
                data-testid={`ver-${asset.id}-${n}`}
              >
                {isImagePath(rel) ? <img src={projectAssetUrl(slug, rel)} alt={`v${n}`} loading="lazy" /> : null}
                <span>v{n}</span>
              </button>
            )
          })}
        </div>
      )}
      <div className="row" style={{ marginTop: 4 }}>
        {asset.kind !== 'voiceRef' && (
          <button onClick={() => setRegen(true)} disabled={regenerating} data-testid={`regen-${asset.id}`}>
            Regenerate
          </button>
        )}
        <button onClick={upload} data-testid={`upload-${asset.id}`}>
          Upload...
        </button>
        <button onClick={() => sendCommand({ type: asset.locked ? 'unlockAsset' : 'lockAsset', slug, id: asset.id })} data-testid={`lock-${asset.id}`}>
          {asset.locked ? 'Unlock' : 'Lock'}
        </button>
        {studio && (
          <button
            onClick={() => sendCommand({ type: 'openInStudio', slug, id: asset.id })}
            disabled={!file || (asset.kind === 'music' && !selectedVersion?.songFile)}
            title={asset.kind === 'music' && !selectedVersion?.songFile ? 'Only music made by Chiptune Studio can be opened there' : `Edit in ${studio}; saving there makes a new version`}
            data-testid={`open-studio-${asset.id}`}
          >
            Open in {studio}
          </button>
        )}
      </div>
      {opened && (
        <div className="dim" data-testid={`studio-opened-${asset.id}`}>
          {opened}
        </div>
      )}
      {regen && <RegenerateDialog asset={asset} slug={slug} onClose={() => setRegen(false)} onSent={() => setPendingRev(rev)} />}
      {zoom && file && (
        <Modal title={asset.id} onClose={() => setZoom(false)} width={900}>
          <img src={projectAssetUrl(slug, file, rev)} alt={asset.id} style={{ maxWidth: '100%', maxHeight: '70vh', objectFit: 'contain' }} />
          <div className="dim" style={{ whiteSpace: 'pre-wrap' }}>
            {asset.prompt}
          </div>
        </Modal>
      )}
    </div>
  )
}

function RegenerateDialog({ asset, slug, onClose, onSent }: { asset: AssetView; slug: string; onClose(): void; onSent(): void }) {
  const engines = useVn((s) => s.engines)
  const workflows = useVn((s) => s.workflows)
  const choices = engineChoices(asset.kind, engines, workflows, asset.engine)
  const [prompt, setPrompt] = useState(asset.prompt)
  const [engine, setEngine] = useState(asset.engine)
  const [seed, setSeed] = useState(asset.seed === null ? '' : String(asset.seed))
  const seedNum = seed.trim() === '' ? undefined : Number(seed)
  const seedBad = seedNum !== undefined && !Number.isInteger(seedNum)
  return (
    <Modal title={`Regenerate ${asset.id}`} onClose={onClose} width={620}>
      <div className="dim">Makes a new version and selects it. The old versions stay in the strip. A build follows.</div>
      <label className="dim">Prompt</label>
      <textarea rows={8} value={prompt} onChange={(e) => setPrompt(e.target.value)} data-testid="regen-prompt" />
      <div className="row">
        <label className="dim">Engine</label>
        <select value={engine} onChange={(e) => setEngine(e.target.value)} data-testid="regen-engine">
          {choices.map((c) => (
            <option key={c.id} value={c.id}>
              {c.label}
            </option>
          ))}
        </select>
        <label className="dim">Seed</label>
        <input value={seed} onChange={(e) => setSeed(e.target.value)} placeholder="random" style={{ width: 130 }} data-testid="regen-seed" />
        <button onClick={() => setSeed(String(Math.floor(Math.random() * 2 ** 31)))}>New seed</button>
      </div>
      {asset.locked && <div className="warn">This asset is locked. Regenerating it by hand still works; unlock it to let the pipeline touch it.</div>}
      <div className="row" style={{ justifyContent: 'flex-end' }}>
        <button onClick={onClose}>Cancel</button>
        <button
          className="primary"
          disabled={seedBad || !prompt.trim()}
          data-testid="regen-go"
          onClick={() => {
            sendCommand({
              type: 'regenerateAsset',
              slug,
              id: asset.id,
              prompt: prompt !== asset.prompt ? prompt : undefined,
              engine: engine !== asset.engine ? engine : undefined,
              seed: seedNum !== undefined && seedNum !== asset.seed ? seedNum : undefined
            })
            onSent()
            onClose()
          }}
        >
          Regenerate
        </button>
      </div>
    </Modal>
  )
}
