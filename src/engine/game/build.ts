/**
 * Builds the standalone HTML5 Visual Novel & Logic Puzzle Web Game.
 * Requires ZERO external Ren'Py SDK!
 */

export interface BuildGameInput {
  projectDir: string
  book: VnBook
  /** Primary first. Editions other than the primary are compiled into the web game. */
  editions: Edition[]
  settings: ProjectSettings
  /** The absolute file of the selected version of an asset, or null when it has none yet (a placeholder is made). */
  resolveAsset: (id: string) => string | null
  /** Music asset id -> loop start in seconds. */
  musicLoops?: (id: string) => number | null | undefined
  /** Voice clips, only when the book has voice on. */
  voice?: VoiceSource
  /** Stage cues; default heuristic is used when omitted. */
  cues?: StageCues
  /** Ren'Py SDK path (optional for the web engine). */
  sdkPath?: string
  resolution?: Resolution
  imageFormat?: ImageFormat
  templateDir?: string
  themesDir?: string
  tintGui?: boolean
  fontsDir?: string
  fontProbe?: Omit<FontProbe, 'fontsDir'>
}

export interface BuildGameResult {
  gameDir: string
  warnings: string[]
  lineMap: LineMapEntry[]
  theme: string
  translated: string[]
  editionsBuilt: string[]
  placeholders: string[]
}

export function defaultTemplateDir(): string {
  return process.env.VNO_TEMPLATES ? path.resolve(process.env.VNO_TEMPLATES) : path.resolve(process.cwd(), 'templates', 'renpy')
}

export const MEDIA_RPY = `# Generated by VN Studio: media channels and transforms
init python:
    renpy.music.register_channel("ambience", mixer="sfx", loop=True)

transform vn_insert:
    xalign 0.5 yalign 0.42
`

export function bookLanguages(primary: Lang, editions: Lang[]): Lang[] {
  return [primary, ...editions.filter((l, i) => l !== primary && editions.indexOf(l) === i)]
}

export function languageTable(primary: Lang, langs: Lang[]): { list: string; defaultLanguage: string } {
  const code = (l: Lang): string => (primary === 'en' && l === 'en' ? 'None' : JSON.stringify(renpyLanguage(l)))
  const list = '[' + langs.map((l) => `(${code(l)}, ${JSON.stringify(nativeName(l))})`).join(', ') + ']'
  return { list, defaultLanguage: primary === 'en' ? 'None' : JSON.stringify(renpyLanguage(primary)) }
}

export function languageWarnings(langs: Lang[]): string[] {
  const out: string[] = []
  for (const code of langs) {
    const name = languageInfo(code)?.name ?? code
    if (code !== 'en' && !uiStrings(code)) {
      out.push(`the menus of ${name} stay in English (no UI strings for ${code}; add them in config/languages.md)`)
    }
  }
  return out
}

export { rtlLanguages }

/**
 * Builds the HTML5 visual novel game into `<projectDir>/game`.
 * Zero Ren'Py SDK required!
 */
export async function buildGame(inp: BuildGameInput): Promise<BuildGameResult> {
  const { projectDir, book, settings } = inp
  const warnings: string[] = [...book.warnings.map((w) => `book: ${w}`)]
  const resolution = inp.resolution ?? { w: 1920, h: 1080 }
  const format: ImageFormat = inp.imageFormat ?? 'webp'
  const themesDir = inp.themesDir ?? defaultThemesDir()
  const gameDir = path.join(path.resolve(projectDir), 'game')
  const sub = path.join(gameDir, 'game')

  // Clean / prepare directories
  fs.rmSync(gameDir, { recursive: true, force: true })
  fs.mkdirSync(gameDir, { recursive: true })
  fs.mkdirSync(sub, { recursive: true })
  for (const d of ['images', 'audio', 'fonts', 'gui']) {
    fs.mkdirSync(path.join(sub, d), { recursive: true })
  }

  // 1. Theme selection & emission
  const available = listThemes(themesDir).themes.map((t) => t.theme.name)
  const themeName = pickTheme(book, settings, available)
  const loaded = findTheme(themeName, themesDir) ?? findTheme(DEFAULT_THEME, themesDir)
  if (!loaded) throw new Error(`No theme found in ${themesDir}`)
  if (settings.theme && settings.theme !== loaded.theme.name) {
    warnings.push(`theme "${settings.theme}" not found; using ${loaded.theme.name}`)
  }

  const themed = await emitTheme({ theme: loaded.theme, themeDir: loaded.dir, gameSubdir: sub })
  warnings.push(...themed.warnings)

  // 2. Fonts resolution
  const allLangs = bookLanguages(book.primaryLang, [book.primaryLang, ...settings.editions, ...inp.editions.map((e) => e.lang)])
  warnings.push(...languageWarnings(allLangs))

  const langFonts = languageFonts({
    gameSubdir: sub,
    langs: allLangs,
    theme: loaded.theme,
    probe: { ...inp.fontProbe, fontsDir: inp.fontsDir }
  })
  warnings.push(...langFonts.warnings)

  const fontsResult = resolveFonts({
    gameDir: sub,
    theme: loaded.theme,
    themeDir: loaded.dir,
    langs: allLangs,
    dataFontsDir: inp.fontsDir,
    probe: { ...inp.fontProbe, fontsDir: inp.fontsDir }
  })
  warnings.push(...fontsResult.warnings)

  // 3. Audio files (Music, SFX, Ambience)
  const music: Record<string, string> = {}
  const musicLoops: Record<string, number | null | undefined> = {}
  const musicIds: string[] = []

  for (let i = 1; i <= Math.max(0, settings.music.tracks); i++) {
    const id = `music_${String(i).padStart(2, '0')}`
    const src = inp.resolveAsset(id)
    if (!src || !fs.existsSync(src)) continue
    const rel = `audio/${id}${path.extname(src) || '.ogg'}`
    fs.copyFileSync(src, path.join(sub, rel))
    music[id] = rel
    musicLoops[id] = inp.musicLoops?.(id)
    musicIds.push(id)
  }

  // Collect sound effects and ambiences played in the book
  const cues = inp.cues ?? defaultCues(book, { musicIds, warn: (m) => warnings.push(m) })
  const playing = new Set<string>()

  for (const ch of book.chapters) {
    for (const sc of ch.scenes) {
      const sceneAmbience = 'ambience' in (cues.scenes[sc.id] ?? {}) ? cues.scenes[sc.id]!.ambience : sc.ambience
      if (sceneAmbience) playing.add(ambId(sceneAmbience))
      for (const b of sc.beats) {
        const bc = cues.beats?.[b.id]
        const sfx = bc?.sfx ?? b.sfx
        const ambience = bc?.ambience !== undefined ? bc.ambience : b.ambience
        if (sfx) playing.add(sfxId(sfx))
        if (ambience) playing.add(ambId(ambience))
      }
    }
  }

  const sounds: Record<string, string> = {}
  for (const id of playing) {
    const src = inp.resolveAsset(id)
    if (!src || !fs.existsSync(src)) continue
    const rel = `audio/${id}${path.extname(src) || '.ogg'}`
    fs.copyFileSync(src, path.join(sub, rel))
    sounds[id] = rel
  }

  // 4. Voice setup
  const usedVoice = new Map<string, string>()
  let voice: VoiceSource | undefined
  if (inp.voice) {
    const src = inp.voice
    voice = {
      has: (lang, beatId) => {
        const f = src.has(lang, beatId)
        if (!f || !fs.existsSync(f)) return null
        usedVoice.set(voicePath(lang, beatId, f), f)
        return f
      }
    }
  }

  // 5. Game Data & Script emission
  const primaryEdition = inp.editions.find((e) => e.lang === book.primaryLang)
  const emitted = emitProject({
    book,
    theme: loaded.theme,
    editions: inp.editions,
    primaryEdition,
    cues,
    voice,
    music,
    musicLoops,
    sounds,
    resolution,
    imageFormat: format,
    pixel: settings.art.style === 'pixel',
    warnings
  })

  // 6. Images (Backgrounds, Sprites, CGs, Cover)
  const images = await buildImages({
    gameSubdir: sub,
    book,
    used: emitted.used,
    resolveAsset: inp.resolveAsset,
    resolution,
    format,
    warnings,
    pixel: settings.art.style === 'pixel',
    pictureBook: isPictureBook(book)
  })

  // 7. Localized Voice copying
  for (const [rel, from] of usedVoice) {
    const target = path.join(sub, rel)
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.copyFileSync(from, target)
  }

  // 8. Write Web Player bundle (index.html, player.css, player.js, game-data.json, game-data.js)
  const themeCss = renderThemeCss(loaded.theme, {
    text: loaded.theme.fonts.text,
    name: loaded.theme.fonts.name ?? loaded.theme.fonts.text,
    interface: loaded.theme.fonts.interface ?? loaded.theme.fonts.text,
    bold: loaded.theme.fonts.bold ?? null
  })
  await writePlayerBundle(sub, emitted.gameData, themeCss)
  fs.writeFileSync(
    path.join(gameDir, 'index.html'),
    '<!DOCTYPE html><html><head><meta http-equiv="refresh" content="0; url=game/index.html"></head></html>',
    'utf8'
  )

  // 9. Legacy compatibility script files
  fs.writeFileSync(path.join(sub, 'vno_media.rpy'), MEDIA_RPY, 'utf8')
  fs.writeFileSync(path.join(sub, 'screens.rpy'), '# Generated by VN Studio\n', 'utf8')

  const table = languageTable(book.primaryLang, allLangs)
  const buildName = book.slug.replace(/[^A-Za-z0-9_-]/g, '_') || 'game'
  const optionsContent = `# Generated by VN Studio
define config.name = "${escapeRenpy(book.title)}"
define config.version = "1.0"
define config.build_name = "${buildName}"
define config.save_directory = "vno-${buildName}"
define gui.show_name = True
define vn_languages = ${table.list}
define config.default_language = ${table.defaultLanguage}
${inp.voice ? 'define vn_voice = True\n' : ''}
`
  fs.writeFileSync(path.join(sub, 'options.rpy'), optionsContent, 'utf8')

  if (langFonts.rpy) {
    fs.writeFileSync(path.join(sub, 'vno_fonts.rpy'), langFonts.rpy, 'utf8')
  }

  const rtl = rtlLanguages(book.primaryLang, allLangs)
  if (rtl.length) {
    const code = (l: Lang): string => (book.primaryLang === 'en' && l === 'en' ? 'None' : renpyLanguage(l))
    fs.writeFileSync(
      path.join(sub, 'vno_rtl.rpy'),
      renderRtl(rtl.map(code), allLangs.filter((l) => !rtl.includes(l)).map(code), resolution.w),
      'utf8'
    )
  }

  if (book.primaryLang !== 'en') {
    writeUiStrings(sub, book.primaryLang)
  }

  const translated: string[] = []
  for (const ed of inp.editions) {
    if (ed.lang === book.primaryLang) continue
    const tlRes = await generateTranslations({
      gameDir: sub,
      book,
      primaryEdition,
      edition: ed,
      lineMap: emitted.lineMap,
      voice,
      warnings
    })
    translated.push(tlRes.language)
  }

  for (const [name, content] of Object.entries(emitted.files)) {
    fs.writeFileSync(path.join(sub, name), content, 'utf8')
  }

  const editionsBuilt = inp.editions.filter((e) => e.lang !== book.primaryLang).map((e) => e.lang)

  return {
    gameDir,
    warnings,
    lineMap: emitted.lineMap,
    theme: loaded.theme.name,
    translated,
    editionsBuilt,
    placeholders: images.placeholders
  }
}
