import type { PuzzleEntry } from '../../shared/puzzle'
import type { VnBook } from '../../shared/vn'
import { renpyString, renpyText } from './escape'
import { cgImageName, spriteImageName } from './images'

/**
 * The puzzles of a book as Ren'Py: `game/vno_puzzles_data.rpy` (`define vno_puzzle_data`), plus the strings a translation can change.
 * The library that plays them (`templates/puzzles/game/`) is copied in by the build only when the book has a puzzle beat.
 *
 * Names and clue texts are written as `_("...")`, so Ren'Py extracts them for translation and the text displayables translate them when
 * they are shown. Everything else is plain data (strings, numbers, lists, dicts): Ren'Py saves and rolls it back.
 */

/** The puzzles that a beat plays, in the order of the book. */
export function playedPuzzles(book: VnBook): PuzzleEntry[] {
  const keys = new Set<string>()
  for (const c of book.chapters) for (const s of c.scenes) for (const b of s.beats) if (b.type === 'puzzle') keys.add(b.puzzle)
  return (book.puzzles ?? []).filter((p) => keys.has(p.key))
}

/** A Python literal of plain data: strings, numbers, booleans, lists and dicts. */
function py(v: unknown): string {
  if (typeof v === 'string') return JSON.stringify(v)
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'True' : 'False'
  if (v === null || v === undefined) return 'None'
  if (Array.isArray(v)) return `[${v.map(py).join(', ')}]`
  return `{${Object.entries(v as Record<string, unknown>)
    .map(([k, x]) => `${JSON.stringify(k)}: ${py(x)}`)
    .join(', ')}}`
}

/** Item id -> the image shown in its header: the neutral sprite of a character, or the picture (an insert) of an object. Places have none. */
export function puzzlePics(book: VnBook, p: PuzzleEntry): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [item, l] of Object.entries(p.links ?? {})) {
    if (l.type === 'character' && book.characters.some((c) => c.key === l.key)) out[item] = spriteImageName(l.key, 'neutral')
    else if (l.type === 'image' && book.images?.some((i) => i.key === l.key)) out[item] = cgImageName(l.key)
  }
  return out
}

/** The dict of one puzzle, the way the screens read it. A clue found earlier in the story has its beat in `at`. */
function entryLiteral(p: PuzzleEntry, pics: Record<string, string>): string {
  const tr = (rec: Record<string, string>) => `{${Object.entries(rec).map(([k, t]) => `${JSON.stringify(k)}: _(${renpyString(t)})`).join(', ')}}`
  const d = p.data
  const parts = [
    `"format": ${d.format}`,
    `"kind": ${py(d.kind)}`,
    `"size": ${d.size}`,
    `"categories": ${py(d.categories)}`,
    `"solution": ${py(d.solution)}`,
    `"clues": ${py(d.clues.map((c) => ({ ...c, ...(p.clueAt?.[c.id] ? { at: p.clueAt[c.id] } : {}) })))}`,
    `"murder": ${py(d.murder)}`,
    `"difficulty": ${py(d.difficulty)}`,
    `"steps": ${py(d.steps)}`,
    `"names": ${tr(p.names)}`,
    `"text": ${tr(p.text)}`,
    `"hints": ${py(p.hints !== false)}`,
    ...(Object.keys(pics).length ? [`"pics": ${py(pics)}`] : []),
    ...(p.onFail ? [`"onFail": ${py(p.onFail)}`] : [])
  ]
  return `{${parts.join(', ')}}`
}

/** `game/vno_puzzles_data.rpy`, or null when no beat plays a puzzle. */
export function emitPuzzleData(book: VnBook): string | null {
  const list = playedPuzzles(book)
  if (!list.length) return null
  return ['# Generated by VN Studio. Do not edit: the next build overwrites this file.', 'define vno_puzzle_data = {', ...list.map((p) => `    ${JSON.stringify(p.key)}: ${entryLiteral(p, puzzlePics(book, p))},`), '}', ''].join('\n')
}

/** The names and clue texts of the played puzzles, for `translate <lang> strings:`. `pick` reads the edition's own words. */
export function puzzleStrings(book: VnBook): { old: string; pick: (e: { puzzles?: Record<string, { names: Record<string, string>; text: Record<string, string> }> }) => string | undefined; what: string }[] {
  const out: ReturnType<typeof puzzleStrings> = []
  for (const p of playedPuzzles(book)) {
    for (const [item, name] of Object.entries(p.names)) out.push({ old: renpyText(name), pick: (e) => e.puzzles?.[p.key]?.names[item], what: `puzzle ${p.key} name of ${item}` })
    for (const [id, text] of Object.entries(p.text)) out.push({ old: renpyText(text), pick: (e) => e.puzzles?.[p.key]?.text[id], what: `puzzle ${p.key} ${id === 'murder' ? 'murder note' : `clue ${id}`}` })
  }
  return out
}
