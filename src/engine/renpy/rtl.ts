/**
 * The right-to-left layout. `config.rtl` makes Ren'Py write text right to left, but the template's layout (the name box on the left, the
 * navigation buttons on the left, the dialogue aligned left ...) stays as it is. The build mirrors it for a right-to-left language with a
 * `translate <language> python:` block that sets the `gui.*` variables below (the way Ren'Py's documentation does it), so the menus of a
 * left-to-right language in the same game are untouched.
 *
 * `ltr` is the value in `templates/renpy/game/gui.rpy` (a test reads the template and checks it), `mirrored` the value for a right-to-left
 * language. `w` is the width of the game screen (1920 for the template).
 *
 * A `translate` python block only runs when the player switches to that language, so the other languages of the game get a block that puts
 * the template values back (Ren'Py's `None`, the source language, is written as `None`).
 */

export interface RtlVariable {
  /** The `gui.` variable. */
  name: string
  /** The value in the template (what a left-to-right language keeps). */
  ltr: number
  /** The value for a right-to-left language at screen width `w`. */
  mirrored: (w: number) => number
}

export const RTL_VARIABLES: readonly RtlVariable[] = [
  { name: 'name_xpos', ltr: 360, mirrored: (w) => w - 360 },
  { name: 'name_xalign', ltr: 0.0, mirrored: () => 1.0 },
  { name: 'dialogue_text_xalign', ltr: 0.0, mirrored: () => 1.0 },
  { name: 'navigation_xpos', ltr: 60, mirrored: (w) => w - 60 },
  { name: 'navigation_xanchor', ltr: 0.0, mirrored: () => 1.0 },
  { name: 'main_menu_text_xalign', ltr: 1.0, mirrored: () => 0.0 },
  { name: 'history_name_xpos', ltr: 233, mirrored: (w) => w - 233 },
  { name: 'history_name_xalign', ltr: 1.0, mirrored: () => 0.0 },
  { name: 'history_text_xpos', ltr: 255, mirrored: (w) => w - 255 },
  { name: 'history_text_xalign', ltr: 0.0, mirrored: () => 1.0 }
]

/** An alignment or anchor is a fraction (`1.0`), a position a pixel count (`1560`): Ren'Py tells them apart by the type, so `1` would mean one pixel. */
const num = (name: string, n: number): string => (/(align|anchor)$/.test(name) ? n.toFixed(1) : String(n))

/**
 * `game/vno_rtl.rpy`: `config.rtl`, the mirrored layout for each right-to-left language (`rtl`: Ren'Py language names) and the template layout
 * for each of the other languages of the game (`ltr`). `width` is the game's screen width. `gui.choice_button_text_xalign` stays centred.
 */
export function renderRtl(rtl: readonly string[], ltr: readonly string[], width: number): string {
  const out = ['# Generated by VN Studio: a right-to-left language is in this game. The layout is mirrored for it only.', 'define config.rtl = True', '']
  const block = (language: string, value: (v: RtlVariable) => number): void => {
    out.push(`translate ${language} python:`)
    for (const v of RTL_VARIABLES) out.push(`    gui.${v.name} = ${num(v.name, value(v))}`)
    out.push('')
  }
  for (const language of rtl) block(language, (v) => v.mirrored(width))
  for (const language of ltr) block(language, (v) => v.ltr)
  return out.join('\n')
}
